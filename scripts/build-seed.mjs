// Generates supabase/seed.sql from src/data/portfolioContent.js.
// Each table is only filled when it is empty, so the seed is safe to run more than once.
import { writeFileSync } from "node:fs";
import * as c from "../src/data/portfolioContent.js";

const q = (v) => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  if (Array.isArray(v) && v.some((x) => x && typeof x === "object")) return `${q(JSON.stringify(v))}::jsonb`;
  if (Array.isArray(v)) return `array[${v.map(q).join(", ")}]::text[]`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

function insert(table, rows, columns) {
  if (!rows.length) return "";
  const values = rows
    .map((row, i) => `  (${columns.map((col) => (col === "sort_order" ? i + 1 : q(row[col]))).join(", ")})`)
    .join(",\n");
  return `insert into public.${table} (${columns.join(", ")})
select * from (values
${values}
) as v(${columns.join(", ")})
where not exists (select 1 from public.${table});\n\n`;
}

const profileCols = Object.keys(c.contactProfile);
let sql = `-- Generated by scripts/build-seed.mjs. Do not edit by hand.\n\n`;
sql += `insert into public.contact_profile (id, ${profileCols.join(", ")})
values (1, ${profileCols.map((k) => q(c.contactProfile[k])).join(", ")})
on conflict (id) do nothing;\n\n`;
sql += insert("hero_images", c.heroImages, ["src", "title", "sort_order"]);
sql += insert("build_items", c.buildItems, ["title", "description", "icon", "color", "sort_order"]);
sql += insert("skill_groups", c.skillGroups, ["title", "color", "skills", "sort_order"]);
sql += insert("experience", c.experience, ["role", "company", "period", "location", "type", "description", "achievements", "technologies", "sort_order"]);
sql += insert("projects", c.projects, ["title", "description", "category", "tags", "image_url", "demo_url", "code_url", "links", "featured", "sort_order"]);
sql += insert("education", c.education, ["title", "institution", "year", "location", "description", "sort_order"]);
sql += insert("certifications", c.certifications, ["title", "issuer", "year", "image_url", "sort_order"]);

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log("Wrote supabase/seed.sql");
